import type { Brief, Finding } from "./types";
import { RUNTIME_LABEL } from "./types";
import { headline } from "./format";

export function toMarkdown(brief: Brief): string {
  const lines: string[] = [];
  lines.push(`# ${brief.checkout}`);
  lines.push("");
  if (brief.identity.description) {
    lines.push(brief.identity.description);
    lines.push("");
  }
  lines.push(headline(brief.findings));
  lines.push("");
  if (brief.location) lines.push(`Checkout: \`${brief.location}\``);
  lines.push(`Stack: ${brief.stack.join(", ") || "unknown"}`);
  if (brief.identity.license) lines.push(`License: ${brief.identity.license}`);
  lines.push("");
  lines.push("## Findings");
  lines.push("");
  if (brief.findings.length === 0) {
    lines.push("The files Foyer compared agree with each other.");
  } else {
    for (const finding of brief.findings) {
      lines.push(`- **${label(finding)}** ${finding.title}. ${finding.detail}`);
    }
  }
  lines.push("");
  lines.push("## How to run it");
  lines.push("");
  if (brief.packageManager) {
    const lock = brief.packageManager.lockfile
      ? `Lockfile: \`${brief.packageManager.lockfile}\`.`
      : "No lockfile was found.";
    lines.push(`Package manager: ${brief.packageManager.name}. ${lock}`);
    lines.push("");
  }
  if (brief.scripts.length === 0) lines.push("No package.json scripts.");
  for (const script of brief.scripts) {
    lines.push(`- \`${script.name}\` — \`${script.command}\``);
  }
  if (brief.makeTargets.length > 0) {
    lines.push("");
    lines.push(`Make targets: ${brief.makeTargets.map((target) => `\`${target.name}\``).join(", ")}`);
  }
  if (brief.services.length > 0) {
    lines.push("");
    for (const service of brief.services) {
      const image = service.image ? ` (${service.image})` : "";
      const ports = service.ports.length > 0 ? ` ports ${service.ports.join(", ")}` : "";
      lines.push(`- Compose \`${service.name}\`${image}${ports}`);
    }
  }
  lines.push("");
  lines.push("## Environment");
  lines.push("");
  if (brief.env.used.length === 0) {
    lines.push("No literal environment reads were found.");
  } else {
    for (const entry of brief.env.used) {
      const where = entry.references
        .slice(0, 3)
        .map((reference) => `${reference.file}:${reference.line}`)
        .join(", ");
      const mark = brief.env.missing.includes(entry.name) ? " — missing from the example" : "";
      lines.push(`- \`${entry.name}\` (${where})${mark}`);
    }
  }
  if (brief.env.stale.length > 0) {
    lines.push("");
    lines.push(`Documented and unread: ${brief.env.stale.map((name) => `\`${name}\``).join(", ")}`);
  }
  lines.push("");
  lines.push("## Runtimes");
  lines.push("");
  if (brief.declarations.length === 0) {
    lines.push("No Node, Python, Go, or Ruby version pin showed up in the usual files.");
  } else {
    for (const declaration of brief.declarations) {
      lines.push(
        `- ${RUNTIME_LABEL[declaration.runtime]} · \`${declaration.file}\` · ${declaration.source} · ${declaration.raw}`,
      );
    }
  }
  lines.push("");
  lines.push("## Automation");
  lines.push("");
  if (brief.workflows.length === 0) lines.push("No GitHub Actions workflows.");
  for (const workflow of brief.workflows) {
    const triggers = workflow.triggers.length > 0 ? workflow.triggers.join(", ") : "unspecified";
    lines.push(`- ${workflow.name} (${workflow.file}) on ${triggers}`);
  }
  lines.push("");
  lines.push("Generated by Foyer from the files in the checkout. Static read only.");
  lines.push("");
  return lines.join("\n");
}

function label(finding: Finding): string {
  if (finding.severity === "attention") return "Attention";
  if (finding.severity === "watch") return "Watch";
  return "Note";
}
